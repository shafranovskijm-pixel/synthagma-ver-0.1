import { setOfflineAuthActor, observeOfflineAccess } from '@/utils/courseCache';
import { act, renderHook } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
const m = vi.hoisted(() => ({ from: vi.fn(), saveAct: vi.fn(), word: vi.fn(), print: vi.fn(), success: vi.fn(), error: vi.fn(), warning: vi.fn(), invalidate: vi.fn(), invoiceInsert: vi.fn() }));
vi.mock('@/integrations/supabase/client', () => ({ supabase: { from: m.from, functions: { invoke: vi.fn() } } }));
vi.mock('@tanstack/react-query', () => ({ useQuery: () => ({ data: { invoices: [], billingDocs: [], contracts: [], orgs: [] }, isLoading: false }), useQueryClient: () => ({ invalidateQueries: m.invalidate }) }));
vi.mock('sonner', () => ({ toast: { success: m.success, error: m.error, warning: m.warning } }));
vi.mock('@/utils/generateAct', () => ({ generateActHtml: vi.fn(), saveActDocument: m.saveAct }));
vi.mock('@/constants/invoiceTemplate', () => ({ generateInvoiceHtml: vi.fn() }));
vi.mock('@/lib/documents/downloadHtmlWord', () => ({ downloadHtmlWord: m.word }));
vi.mock('@/utils/printHtmlToPdf', () => ({ printHtmlContent: m.print }));
import { useAdminBilling } from '../useAdminBilling';
const pending = { html: '<p>Синтетический акт QA</p>', actNumber: 'QA-1', docName: 'QA акт', organizationId: 'QA-org', basis: 'Синтетический QA' };
beforeEach(() => { setOfflineAuthActor(null); vi.clearAllMocks(); m.invalidate.mockReset().mockResolvedValue(undefined); m.invoiceInsert.mockReset().mockResolvedValue({ error: null }); m.from.mockReset().mockReturnValue({ insert: m.invoiceInsert }); m.saveAct.mockReset().mockResolvedValue('QA акт'); m.word.mockReset().mockResolvedValue(true); m.print.mockReset().mockResolvedValue(undefined); });
describe('saved document and output are separate outcomes', () => {
    it('does not download, print, clear the pending act, or claim success when the registry save fails', async () => {
        m.saveAct.mockResolvedValue(null);
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingAct(pending));
        await act(async () => { await h.result.current.handleSavePendingAct('download'); });
        expect(m.word).not.toHaveBeenCalled();
        expect(m.print).not.toHaveBeenCalled();
        expect(m.success).not.toHaveBeenCalled();
        expect(h.result.current.pendingAct).toEqual(pending);
        expect(m.error).toHaveBeenCalled();
    });
    it('coalesces repeated clicks during one registry save and keeps its successful record when Word fails', async () => {
        let done!: (name: string) => void;
        m.saveAct.mockImplementation(() => new Promise(resolve => { done = resolve; }));
        m.word.mockResolvedValue(false);
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingAct(pending));
        let first!: Promise<void>;
        await act(async () => { first = h.result.current.handleSavePendingAct('download'); await h.result.current.handleSavePendingAct('download'); });
        expect(m.saveAct).toHaveBeenCalledOnce();
        await act(async () => { done('QA акт'); await first; });
        expect(m.word).toHaveBeenCalledOnce();
        expect(m.success).not.toHaveBeenCalled();
        expect(m.warning).toHaveBeenCalledWith(expect.stringContaining('повторите выгрузку существующего акта'));
        expect(h.result.current.pendingAct).toBeNull();
        expect(m.saveAct).toHaveBeenCalledOnce();
    });
    it('does not say print was completed after a failed browser print handoff', async () => {
        m.print.mockRejectedValue(new Error('Print unavailable'));
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingAct(pending));
        await act(async () => { await h.result.current.handleSavePendingAct('print'); });
        expect(m.saveAct).toHaveBeenCalledOnce();
        expect(m.success).not.toHaveBeenCalled();
        expect(m.warning).toHaveBeenCalledWith(expect.stringContaining('Акт уже сохранён'), expect.anything());
        expect(h.result.current.pendingAct).toBeNull();
    });
    it('consumes exactly the persisted act before a post-save access fence fails and never offers a duplicate save', async () => {
        setOfflineAuthActor('QA-A');
        let done!: (name: string) => void;
        m.saveAct.mockImplementation(() => new Promise(resolve => { done = resolve; }));
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingAct(pending));
        let first!: Promise<void>;
        await act(async () => { first = h.result.current.handleSavePendingAct('download'); });
        observeOfflineAccess('QA-A', 'access-changed');
        await act(async () => { done('QA акт'); await first; });
        expect(h.result.current.pendingAct).toBeNull();
        expect(m.word).not.toHaveBeenCalled();
        expect(m.print).not.toHaveBeenCalled();
        expect(m.saveAct).toHaveBeenCalledOnce();
        expect(m.warning).toHaveBeenCalledWith(expect.stringContaining('Акт уже сохранён'), expect.anything());
        await act(async () => { await h.result.current.handleSavePendingAct('download'); });
        expect(m.saveAct).toHaveBeenCalledOnce();
    });
    it('does not clear a newer act draft when an earlier save completes', async () => {
        let done!: (name: string) => void;
        m.saveAct.mockImplementation(() => new Promise(resolve => { done = resolve; }));
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingAct(pending));
        let first!: Promise<void>;
        await act(async () => { first = h.result.current.handleSavePendingAct('download'); });
        const newer = { ...pending, actNumber: 'QA-2', docName: 'Новый QA акт' };
        act(() => h.result.current.setPendingAct(newer));
        await act(async () => { done('QA акт'); await first; });
        expect(h.result.current.pendingAct).toEqual(newer);
        expect(m.word).toHaveBeenCalledWith(pending.html, pending.docName + '.docx');
        expect(m.saveAct).toHaveBeenCalledOnce();
    });
    it('consumes a confirmed invoice before refresh failure and never inserts it again on retry', async () => {
        m.invalidate.mockRejectedValueOnce(new Error('Refresh unavailable'));
        const h = renderHook(() => useAdminBilling());
        act(() => h.result.current.setPendingInvoice({ html: '<p>QA invoice</p>', insertData: { organization_id: 'QA-org', invoice_number: 'QA-1' }, invoiceNum: 'QA-1', amount: 4490, plan: 'start' }));
        await act(async () => { await h.result.current.handleSavePendingInvoice('download'); });
        expect(h.result.current.pendingInvoice).toBeNull();
        expect(m.invoiceInsert).toHaveBeenCalledOnce();
        expect(m.word).not.toHaveBeenCalled();
        expect(m.warning).toHaveBeenCalledWith(expect.stringContaining('Счёт уже сохранён'), expect.anything());
        await act(async () => { await h.result.current.handleSavePendingInvoice('download'); });
        expect(m.invoiceInsert).toHaveBeenCalledOnce();
    });
});
afterEach(() => setOfflineAuthActor(null));
