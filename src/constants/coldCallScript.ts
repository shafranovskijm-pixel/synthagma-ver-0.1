export interface ScriptContext {
  companyName?: string;
  managerName?: string;
  contactName?: string;
  phone?: string;
  /** Alias для companyName (обратная совместимость). */
  leadName?: string;
}

/** Подставляет переменные {company_name}, {manager_name}, {contact_name}, {phone}
 *  плюс поддерживает legacy-плейсхолдеры [Имя]/[Менеджер]. */
export function fillScriptTemplate(text: string, ctx: ScriptContext = {}): string {
  const company = ctx.companyName || ctx.leadName || 'компания';
  const manager = ctx.managerName || '[ваше имя]';
  const contact = ctx.contactName || 'коллега';
  const phone = ctx.phone || '';
  return text
    .replace(/\{company_name\}/g, company)
    .replace(/\{manager_name\}/g, manager)
    .replace(/\{contact_name\}/g, contact)
    .replace(/\{phone\}/g, phone)
    .replace(/\[Имя\]/g, contact)
    .replace(/\[Менеджер\]/g, manager);
}
