// Подставляет [Имя], [Менеджер] в тексты скрипта.
export function fillScriptTemplate(text: string, ctx: { leadName?: string; managerName?: string }): string {
  return text
    .replace(/\[Имя\]/g, ctx.leadName || 'коллега')
    .replace(/\[Менеджер\]/g, ctx.managerName || '[ваше имя]');
}
