/**
 * Шаблон Соглашения о простой электронной подписи (ПЭП).
 * Соответствует требованиям 63-ФЗ "Об электронной подписи" (ст. 6, 9)
 * и 152-ФЗ "О персональных данных".
 */

export const PEP_AGREEMENT_VERSION = "v1.0";

export interface PepAgreementVars {
  org_name: string;
  org_inn?: string;
  org_address?: string;
  user_name: string;
  user_email: string;
  current_date: string;
}

const TEMPLATE = `СОГЛАШЕНИЕ
об использовании простой электронной подписи (ПЭП)

г. ____________                                          {{current_date}}

{{org_name}}{{org_inn_part}}, именуемое в дальнейшем «Оператор», с одной стороны, и {{user_name}} (e-mail: {{user_email}}), именуемый(ая) в дальнейшем «Пользователь», с другой стороны, совместно именуемые «Стороны», заключили настоящее Соглашение о нижеследующем.

1. ПРЕДМЕТ СОГЛАШЕНИЯ
1.1. Настоящее Соглашение регулирует отношения между Сторонами по использованию простой электронной подписи (далее — «ПЭП») при подписании электронных документов в рамках сервиса Оператора.
1.2. Соглашение заключено в соответствии с Федеральным законом от 06.04.2011 № 63-ФЗ «Об электронной подписи» (далее — «63-ФЗ»), статьями 5, 6, 9.

2. ОПРЕДЕЛЕНИЯ
2.1. Простая электронная подпись (ПЭП) — электронная подпись, которая посредством использования кодов, паролей или иных средств подтверждает факт формирования электронной подписи определённым лицом (п. 2 ст. 5 63-ФЗ).
2.2. Ключ ПЭП — уникальная комбинация логина (e-mail Пользователя: {{user_email}}) и пароля учётной записи Пользователя в сервисе Оператора.
2.3. Электронный документ — документ в электронной форме, подписанный ПЭП Пользователя.

3. ПРАВИЛА ОПРЕДЕЛЕНИЯ ПОДПИСАНТА
3.1. Лицом, подписавшим электронный документ ПЭП, признаётся Пользователь, чей ключ ПЭП (логин и пароль) был использован для входа в учётную запись и подтверждения подписания.
3.2. Факт подписания фиксируется в журнале операций Оператора с указанием:
    – идентификатора Пользователя и e-mail;
    – даты и времени подписания (по UTC и МСК);
    – IP-адреса устройства;
    – User-Agent (тип браузера/устройства);
    – SHA-256 хеша содержимого подписанного документа.

4. ОБЯЗАННОСТИ ПОЛЬЗОВАТЕЛЯ
4.1. Пользователь обязуется обеспечивать конфиденциальность ключа ПЭП (пароля учётной записи) и не передавать его третьим лицам.
4.2. В случае компрометации ключа ПЭП (утечка пароля, несанкционированный доступ) Пользователь обязан незамедлительно уведомить Оператора и сменить пароль.
4.3. До момента уведомления Оператора все действия, совершённые с использованием ключа ПЭП Пользователя, считаются совершёнными самим Пользователем.

5. РАВНАЯ ЮРИДИЧЕСКАЯ СИЛА
5.1. Стороны признают, что электронные документы, подписанные ПЭП в порядке, установленном настоящим Соглашением, ЭКВИВАЛЕНТНЫ документам на бумажном носителе, подписанным собственноручной подписью (п. 2 ст. 6 63-ФЗ).
5.2. Документы, подписанные ПЭП, имеют полную юридическую силу, могут быть представлены в суд и иные органы в качестве доказательств.

6. ВИДЫ ДОКУМЕНТОВ, ПОДПИСЫВАЕМЫХ ПЭП
В рамках настоящего Соглашения с использованием ПЭП Стороны вправе подписывать следующие виды документов:
    – согласия на обработку персональных данных и иные согласия;
    – договоры на оказание образовательных услуг и приложения к ним;
    – акты сдачи-приёмки оказанных услуг;
    – счета и иные расчётные документы;
    – приказы о зачислении/отчислении/выдаче документов об образовании;
    – заявления, уведомления и иные документы, обмен которыми предусмотрен между Сторонами.

7. ПОРЯДОК ПРОВЕРКИ ПОДПИСИ
7.1. Проверка ПЭП осуществляется путём сверки данных, зафиксированных в журнале операций Оператора, с метаданными подписанного документа.
7.2. Целостность подписанного документа подтверждается совпадением SHA-256 хеша содержимого документа с хешем, зафиксированным в момент подписания.
7.3. Оператор обеспечивает хранение журнала операций и подписанных документов в течение не менее 5 (пяти) лет с момента подписания.

8. ОГРАНИЧЕНИЯ
8.1. ПЭП НЕ применяется в случаях, когда законодательством Российской Федерации прямо предусмотрено использование квалифицированной электронной подписи (КЭП), в частности:
    – при подаче документов в государственные органы, требующие КЭП;
    – при заключении сделок, для которых нотариальная форма обязательна;
    – в иных случаях, прямо предусмотренных законом.

9. ОБРАБОТКА ПЕРСОНАЛЬНЫХ ДАННЫХ
9.1. Подписывая настоящее Соглашение, Пользователь подтверждает согласие на обработку Оператором его персональных данных (ФИО, e-mail, IP-адрес, User-Agent, метаданные подписания) в целях реализации настоящего Соглашения в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных».

10. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ
10.1. Настоящее Соглашение вступает в силу с момента его принятия Пользователем (проставление отметки о согласии в интерфейсе сервиса) и действует бессрочно до момента его расторжения одной из Сторон.
10.2. Версия Соглашения: ${PEP_AGREEMENT_VERSION}.

ОПЕРАТОР: {{org_name}}{{org_inn_part}}
ПОЛЬЗОВАТЕЛЬ: {{user_name}} ({{user_email}})
`;

export function getPepAgreementText(vars: PepAgreementVars): string {
  const innPart = vars.org_inn ? ` (ИНН ${vars.org_inn})` : "";
  const repl = (s: string, k: string, v: string) => s.split(k).join(v);
  let out = TEMPLATE;
  out = repl(out, "{{org_name}}", vars.org_name);
  out = repl(out, "{{org_inn_part}}", innPart);
  out = repl(out, "{{user_name}}", vars.user_name);
  out = repl(out, "{{user_email}}", vars.user_email);
  out = repl(out, "{{current_date}}", vars.current_date);
  return out;
}

export function getPepAgreementHtml(vars: PepAgreementVars): string {
  const text = getPepAgreementText(vars);
  const safe = text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
  return `<div style="font-family: 'Times New Roman', serif; font-size: 14px; line-height: 1.6; color: #111; padding: 40px; max-width: 800px; margin: 0 auto; background: #fff; white-space: pre-wrap;">${safe}</div>`;
}
