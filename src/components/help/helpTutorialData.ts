function normalize(value: string): string {
  return value.trim().toLocaleLowerCase("ru-RU");
}

export function filterHelpTutorials(
  query: string,
  tutorials: HelpTutorial[] = helpTutorials,
): HelpTutorial[] {
  const normalizedQuery = normalize(query);
  if (!normalizedQuery) return tutorials;

  return tutorials.filter((tutorial) => {
    const searchable = [
      tutorial.title,
      tutorial.summary,
      tutorial.section,
      ...tutorial.keywords,
      ...tutorial.steps.flatMap((step) => [
        step.title,
        step.description,
        step.note || "",
        ...(step.screenshots || []).flatMap((screenshot) => [
          screenshot.alt,
          screenshot.caption || "",
        ]),
      ]),
    ];

    return searchable.some((value) => normalize(value).includes(normalizedQuery));
  });
}
