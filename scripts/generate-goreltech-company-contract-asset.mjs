import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const assetDir = path.join(
  root,
  "supabase",
  "functions",
  "_shared",
  "contract-templates",
  "goreltech",
  "company",
  "v1",
);

const [template, manifest] = await Promise.all([
  readFile(path.join(assetDir, "template.docx")),
  readFile(path.join(assetDir, "manifest.json"), "utf8"),
]);

const generated = `// Auto-generated by scripts/generate-goreltech-company-contract-asset.mjs.
// The retained DOCX and manifest remain the editable source of truth.
export const GORELTECH_COMPANY_CONTRACT_TEMPLATE_BASE64 = ${JSON.stringify(template.toString("base64"))};
export const GORELTECH_COMPANY_CONTRACT_MANIFEST_JSON = ${JSON.stringify(manifest)};
`;

await writeFile(path.join(assetDir, "embedded.ts"), generated, "utf8");
