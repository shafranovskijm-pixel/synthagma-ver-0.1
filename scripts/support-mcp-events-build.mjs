import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';

const SDK_VERSION = '0.23.0';
const BANNER = '// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.';
const ANCHOR = 'Deno.serve(createSupabaseHandler(mcp_default, { functionName: "mcp" }));';
const IMPORT = 'import { withSupportMcpEvents } from "../_shared/support-mcp-events/runtime.bundle.mjs";';
const WRAPPED = 'Deno.serve(withSupportMcpEvents(createSupabaseHandler(mcp_default, { functionName: "mcp" })));';
const MARKER = '// SINTAGMA_SUPPORT_MCP_EVENTS_POSTBUILD_V1';
const SHA = value => createHash('sha256').update(value).digest('hex');
const count = (value, token) => value.split(token).length - 1;

/** Narrow SDK-shape guard: never search-and-replace an unknown handler or tool bundle. */
export function wrapGeneratedMcp(source) {
  if (!source.startsWith(`${BANNER}\n`) || count(source, 'Deno.serve(') !== 1 ||
      count(source, 'import { createSupabaseHandler } from "npm:@lovable.dev/mcp-js@0.23.0/stacks/supabase";') !== 1) {
    throw new Error('unsupported_mcp_sdk_entry_shape');
  }
  if (source.includes(MARKER) || source.includes(IMPORT) || source.includes('withSupportMcpEvents(')) {
    if (count(source, MARKER) !== 1 || count(source, IMPORT) !== 1 || count(source, WRAPPED) !== 1 ||
        count(source, ANCHOR) !== 0 || count(source, 'withSupportMcpEvents(') !== 1 ||
        !source.includes(`${MARKER}\n${IMPORT}\n${WRAPPED}`)) {
      throw new Error('unsupported_mcp_sdk_wrapped_shape');
    }
    return source;
  }
  if (count(source, ANCHOR) !== 1) throw new Error('unsupported_mcp_sdk_entry_anchor');
  return source.replace(ANCHOR, `${MARKER}\n${IMPORT}\n${WRAPPED}`);
}
function inside(root, relative) {
  const file = path.resolve(root, relative);
  const rel = path.relative(root, file);
  if (rel.startsWith('..') || path.isAbsolute(rel)) throw new Error('invalid_build_target');
  return file;
}
export async function buildSupportMcpEvents(rootDir, options = {}) {
  const root = path.resolve(rootDir);
  const require = createRequire(inside(root, 'package.json'));
  // package.json is not exported by SDK0.23. Resolve its documented dist entry instead.
  const sdkEntry = require.resolve('@lovable.dev/mcp-js');
  const sdkPath = path.resolve(path.dirname(sdkEntry), '..', 'package.json');
  const sdk = JSON.parse(await fs.readFile(sdkPath, 'utf8'));
  if (sdk.name !== '@lovable.dev/mcp-js' || sdk.version !== SDK_VERSION) throw new Error('unsupported_mcp_sdk_version');
  const input = inside(root, 'supabase/functions/mcp/index.ts');
  const adapter = inside(root, 'supabase/functions/_shared/support-mcp-events/runtime-entry.ts');
  const output = inside(root, 'supabase/functions/_shared/support-mcp-events/runtime.bundle.mjs');
  const original = await fs.readFile(input, 'utf8');
  const wrapped = wrapGeneratedMcp(original);
  const esbuild = options.esbuild ?? require('esbuild');
  const bundle = await esbuild.build({
    entryPoints: [adapter], bundle: true, write: false, outfile: output,
    platform: 'neutral', format: 'esm', target: 'es2022', sourcemap: false,
    legalComments: 'none', logLevel: 'silent', external: ['node:*'],
    plugins: [{ name: 'sintagma-deno-supabase-external', setup(build) {
      build.onResolve({ filter: /^@supabase\/supabase-js$/ }, () => ({ path: 'npm:@supabase/supabase-js@2.90.1', external: true }));
    } }],
  });
  if (!bundle.outputFiles || bundle.outputFiles.length !== 1) throw new Error('unexpected_mcp_adapter_bundle');
  const bytes = bundle.outputFiles[0].contents;
  // Produce the referenced module first; only then introduce the import into the generated file.
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.writeFile(output, bytes);
  if (wrapped !== original) await fs.writeFile(input, wrapped, 'utf8');
  return { sdkVersion: sdk.version, wrapperVersion: 1, adapterSha256: SHA(bytes),
    entrySha256: SHA(wrapped), sourceEntrySha256: SHA(original), alreadyWrapped: wrapped === original };
}
/** A sequential post hook runs after the SDK's generated handler write. */
export function supportMcpEventsBuildPlugin(rootDir) {
  return {
    name: 'sintagma-support-mcp-events-postbuild', enforce: 'post', apply: 'build',
    closeBundle: { order: 'post', sequential: true, async handler() { await buildSupportMcpEvents(rootDir); } },
  };
}
