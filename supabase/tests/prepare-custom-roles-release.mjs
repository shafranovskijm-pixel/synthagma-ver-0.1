// Deterministic SQL-editor transaction; never connects to a database.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const folder=root+'docs/releases/sintagma-production/staff-custom-roles-20261012/';
const source=await readFile(root+'supabase/migrations/20261012123000_org_custom_roles_staff_permissions.sql','utf8');
const md5=createHash('md5').update(source.replaceAll('\r\n','\n')).digest('hex');
const backup=(await readFile(folder+'backup-definitions.sql','utf8')).replace(/^--[^\n]*\n/,'').trim().replace(/;$/,'');
const checks=(await readFile(folder+'postcheck.sql','utf8')).trim().replace(/;$/,'');
const guard=source.slice(source.indexOf('DO $preflight$'),source.indexOf('END $preflight$;')+'END $preflight$;'.length);
await writeFile(folder+'preflight.sql','-- Read-only catalog assertions. No production rows or schema objects are changed.\n'+guard+'\nSELECT NOT EXISTS(SELECT 1 FROM supabase_migrations.schema_migrations WHERE version=\'20261012123000\') AS version_absent;\n');
const sql=`-- Generated by supabase/tests/prepare-custom-roles-release.mjs. Send as ONE request.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='120s';
SELECT pg_advisory_xact_lock(hashtextextended('sintagma-production-release',0));
LOCK TABLE supabase_migrations.schema_migrations IN SHARE ROW EXCLUSIVE MODE;
DO $ledger$ BEGIN
 IF EXISTS(SELECT 1 FROM supabase_migrations.schema_migrations WHERE version='20261012123000')
 THEN RAISE EXCEPTION 'Custom-role migration replay refused'; END IF;
END $ledger$;
${guard}
CREATE TEMP TABLE custom_roles_security_before ON COMMIT DROP AS ${backup};
CREATE TEMP TABLE custom_roles_release_result(result jsonb) ON COMMIT PRESERVE ROWS;
DO $apply$
DECLARE source text := $custom_roles_source$${source}$custom_roles_source$;
BEGIN
 IF md5(replace(source,chr(13)||chr(10),chr(10)))<>'${md5}' THEN RAISE EXCEPTION 'Custom-role source hash mismatch'; END IF;
 EXECUTE source;
 INSERT INTO supabase_migrations.schema_migrations(version,name,statements)
 VALUES('20261012123000','org_custom_roles_staff_permissions',ARRAY[source]);
END $apply$;
DO $postcheck$
DECLARE r record; checks integer:=0; after_security jsonb;
BEGIN
 FOR r IN ${checks} LOOP
  IF r.ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'Custom-role postcheck failed: %',r.check_name; END IF;
  checks:=checks+1;
 END LOOP;
 SELECT custom_roles_backup INTO after_security FROM (${backup}) q;
 IF (after_security-'policies') IS DISTINCT FROM (SELECT custom_roles_backup-'policies' FROM custom_roles_security_before)
 THEN RAISE EXCEPTION 'Unrelated custom-role security objects changed'; END IF;
 IF NOT EXISTS(SELECT 1 FROM supabase_migrations.schema_migrations WHERE version='20261012123000'
   AND name='org_custom_roles_staff_permissions' AND cardinality(statements)=1
   AND md5(replace(statements[1],chr(13)||chr(10),chr(10)))='${md5}')
 THEN RAISE EXCEPTION 'Custom-role ledger source mismatch'; END IF;
 INSERT INTO custom_roles_release_result VALUES(jsonb_build_object('committed',true,'version','20261012123000',
   'checks_passed',checks,'preserved_security',true,'ledger_source_match',true,'transaction_id',txid_current()));
END $postcheck$;
NOTIFY pgrst,'reload schema';
COMMIT;
SELECT result AS release_result FROM custom_roles_release_result;
`;
await writeFile(folder+'release-transaction.sql',sql);
console.log(JSON.stringify({migrationMd5:md5,bundleSha256:createHash('sha256').update(sql).digest('hex')}));
